#ifndef HPM_IMU__YESENSE_FRAME_PARSER_HPP_
#define HPM_IMU__YESENSE_FRAME_PARSER_HPP_

#include "hpm_transport/frame.hpp"

#include <array>
#include <cstdint>

namespace hpmImu
{

constexpr uint8_t kMsgIdAcceleration = 0x30U;
constexpr uint8_t kMsgIdGyroscope = 0x31U;
constexpr uint8_t kMsgIdEuler = 0x32U;
constexpr uint8_t kMsgIdQuaternion = 0x33U;
constexpr double kYesenseScale = 0.000001;

struct ImuSample
{
  std::array<double, 3> acceleration_mps2{};
  std::array<double, 3> angular_velocity_deg_s{};
  std::array<double, 3> euler_deg{};
  std::array<double, 4> quaternion{};
};

/**
 * Parses the four fixed-size ENET IMU payloads generated by the board.
 *
 * The board has already parsed the variable-length YIS320 UART protocol.
 * This class therefore consumes frameTransport::Frame::payload, not raw UART
 * bytes. A complete sample is emitted when a quaternion frame (0x33) arrives
 * after all four data types have been received.
 */
class YesenseFrameParser
{
public:
  /**
   * Consume one ENET frame.
   *
   * @param frame ENET frame received from hpm_transport.
   * @param sample receives a sample only when this function returns true.
   * @return true when a complete ACC/GYRO/EULER/QUAT sample was completed.
   */
  bool feed(const frameTransport::Frame & frame, ImuSample & sample);

  void reset();

private:
  static int32_t read_be_i32(const uint8_t * data);
  static void decode_vec3(const std::array<uint8_t, frameTransport::kFramePayloadLen> & payload,
                          std::array<double, 3> & output);
  static void decode_quaternion(
    const std::array<uint8_t, frameTransport::kFramePayloadLen> & payload,
    std::array<double, 4> & output);

  ImuSample current_{};
  bool have_acceleration_{false};
  bool have_gyroscope_{false};
  bool have_euler_{false};
  bool have_quaternion_{false};
};

}  // namespace hpmImu

#endif  // HPM_IMU__YESENSE_FRAME_PARSER_HPP_
